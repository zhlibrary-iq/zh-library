-- Run this SQL in Supabase Dashboard > SQL Editor.
create table if not exists public.designs (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null check (category in ('pc','mobile','gifts','banners','static')),
  price text default '',
  url text not null,
  file_type text default '',
  storage_path text,
  is_new boolean default false,
  created_at timestamptz not null default now()
);
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text default 'عميل',
  rating integer not null check (rating between 1 and 5),
  comment text default '',
  created_at timestamptz not null default now()
);
-- Public can view gallery and reviews; visitors can submit reviews. Only authenticated admins can add/delete designs.
alter table public.designs enable row level security;
alter table public.reviews enable row level security;
drop policy if exists "Public read designs" on public.designs;
create policy "Public read designs" on public.designs for select using (true);
drop policy if exists "Authenticated manage designs" on public.designs;
create policy "Authenticated manage designs" on public.designs for all to authenticated using (true) with check (true);
drop policy if exists "Public read reviews" on public.reviews;
create policy "Public read reviews" on public.reviews for select using (true);
drop policy if exists "Public submit reviews" on public.reviews;
create policy "Public submit reviews" on public.reviews for insert with check (rating between 1 and 5 and length(coalesce(comment,'')) <= 400 and length(coalesce(name,'')) <= 40);
-- Storage bucket for portfolio media.
insert into storage.buckets (id,name,public) values ('design-assets','design-assets',true) on conflict (id) do update set public=true;
drop policy if exists "Public view design assets" on storage.objects;
create policy "Public view design assets" on storage.objects for select using (bucket_id='design-assets');
drop policy if exists "Authenticated upload design assets" on storage.objects;
create policy "Authenticated upload design assets" on storage.objects for insert to authenticated with check (bucket_id='design-assets');
drop policy if exists "Authenticated delete design assets" on storage.objects;
create policy "Authenticated delete design assets" on storage.objects for delete to authenticated using (bucket_id='design-assets');
